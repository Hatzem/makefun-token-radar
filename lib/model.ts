// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, through category comparables:
//
//   compRatio  = median(mcap_usd / tvl_usd) of live-token protocols in the same category,
//                when that category has at least COMP_MIN_LIVE live protocols; otherwise the
//                global median over all live-token protocols. Winsorized to [0.01, 2.5] so one
//                outlier category cannot dominate the board.
//   base       = tvl_usd x compRatio
//   growth     = clamp(change_7d, -30, 60) per cent; unreported growth counts as 0
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.7 + min(age_days, 1095) / 1095 x 0.3; unknown age is neutral at 0.85
//   chainMult  = 1 + 0.015 x min(chains - 1, 10), capped at 1.15
//   implied    = max(1, round(base x growthMult x maturity x chainMult))
//
// No protocol name is ever special-cased: the same function scores every row. After sorting, a
// one-dollar tie-break keeps implied values strictly decreasing with rank.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

